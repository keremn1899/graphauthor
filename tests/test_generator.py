class StructuralTestGenerator:
    """Generates test cases by walking graph topology. Ground truth is structural."""

    def __init__(self, conn: lb.Connection, structural_index: dict[str, StructuralFacts], graph_id: str):
        self.conn = conn
        self.si = structural_index
        self.graph_id = graph_id
        self.labels = _label_map(conn)
        self._llm: ChatOpenAI | None = None

    def _get_llm(self) -> ChatOpenAI:
        if self._llm is None:
            self._llm = _fast_llm()
        return self._llm

    def _node_anchor_words(self, node_id: str) -> list[str]:
        """Extract a few key terms from a node's anchor for must_contain hints."""
        rows = list(self.conn.execute(
            "MATCH (c:Concept {id: $id}) RETURN c.semantic_anchor, c.label",
            {"id": node_id},
        ))
        if not rows:
            return []
        anchor, label = rows[0][0] or "", rows[0][1] or ""
        # Return the label words as must_contain hints (conservative)
        return [w for w in label.split() if len(w) > 4]

    def generate_causal_forward(self) -> list[TestCase]:
        cases: list[TestCase] = []
        origins = [nid for nid, f in self.si.items()
                   if "causal_origin" in f.roles or "causal_nexus" in f.roles]
        for node_id in origins:
            chain = _traverse_chain(self.conn, node_id, "forward", "leadsto", max_depth=4)
            if len(chain) < 2:
                continue
            label = self.labels.get(node_id, node_id)
            terminal_label = self.labels.get(chain[-1], chain[-1])
            variants = _generate_query_variants(
                self._get_llm(), "causal_forward", label,
                context=f"The chain ends at: {terminal_label}"
            )
            trail = _format_trail(chain, self.labels, "LEADSTO")
            must_contain = self._node_anchor_words(chain[-1])[:2]
            for q in variants:
                cases.append(TestCase(
                    id=f"sf_{uuid.uuid4().hex[:8]}",
                    query=q,
                    query_type="causal_forward",
                    authored_by="structural_generator",
                    graph_id=self.graph_id,
                    source_node=node_id,
                    ground_truth=GroundTruth(
                        required_nodes=chain,
                        required_trail=trail,
                        answer_must_contain=must_contain,
                        answerable=True,
                        difficulty="multi_hop" if len(chain) > 2 else "single_hop",
                        notes=f"Causal chain of length {len(chain)} from {label}",
                    ),
                ))
        return cases

    def generate_causal_backward(self) -> list[TestCase]:
        cases: list[TestCase] = []
        terminals = [nid for nid, f in self.si.items()
                     if "causal_terminal" in f.roles]
        for node_id in terminals:
            chain = _traverse_chain(self.conn, node_id, "backward", "leadsto", max_depth=4)
            if len(chain) < 2:
                continue
            label = self.labels.get(node_id, node_id)
            variants = _generate_query_variants(
                self._get_llm(), "causal_backward", label,
            )
            # Reverse chain so it reads cause → effect
            chain_rev = list(reversed(chain))
            trail = _format_trail(chain_rev, self.labels, "LEADSTO")
            must_contain = self._node_anchor_words(chain[-1])[:2]
            for q in variants:
                cases.append(TestCase(
                    id=f"sb_{uuid.uuid4().hex[:8]}",
                    query=q,
                    query_type="causal_backward",
                    authored_by="structural_generator",
                    graph_id=self.graph_id,
                    source_node=node_id,
                    ground_truth=GroundTruth(
                        required_nodes=chain_rev,
                        required_trail=trail,
                        answer_must_contain=must_contain,
                        answerable=True,
                        difficulty="multi_hop" if len(chain) > 2 else "single_hop",
                        notes=f"Backward chain from terminal {label}",
                    ),
                ))
        return cases

    def generate_bridge(self) -> list[TestCase]:
        """Find pairs of causal_origin nodes and check for paths between them."""
        cases: list[TestCase] = []
        bridges = [nid for nid, f in self.si.items()
                   if "inter_region_bridge" in f.roles]
        origins = [nid for nid, f in self.si.items()
                   if "causal_origin" in f.roles]

        # For each bridge node: try to find a path from any origin to it
        for bridge_id in bridges[:3]:  # cap at 3 bridge queries
            bridge_label = self.labels.get(bridge_id, bridge_id)
            if not origins:
                continue
            src_id = origins[0]
            src_label = self.labels.get(src_id, src_id)
            paths = find_paths(self.conn, src_id, bridge_id, max_hops=5)
            if not paths:
                continue
            best = paths[0]
            node_chain = best.get("node_chain", [src_id, bridge_id])
            edge_chain = best.get("edge_chain", [])
            trail = []
            for i in range(len(node_chain) - 1):
                etype = edge_chain[i].upper() if i < len(edge_chain) else "?"
                trail.append(
                    f"{self.labels.get(node_chain[i], node_chain[i])} --{etype}--> "
                    f"{self.labels.get(node_chain[i+1], node_chain[i+1])}"
                )
            variants = _generate_query_variants(
                self._get_llm(), "bridge",
                f"{src_label} and {bridge_label}",
                context="Find the connection between these two concepts",
            )
            must_contain = (
                self._node_anchor_words(bridge_id)[:1]
                + self._node_anchor_words(src_id)[:1]
            )
            for q in variants:
                cases.append(TestCase(
                    id=f"sbr_{uuid.uuid4().hex[:8]}",
                    query=q,
                    query_type="bridge",
                    authored_by="structural_generator",
                    graph_id=self.graph_id,
                    source_node=bridge_id,
                    ground_truth=GroundTruth(
                        required_nodes=node_chain,
                        required_trail=trail,
                        answer_must_contain=must_contain,
                        answerable=True,
                        difficulty="bridge",
                        notes=f"Bridge path via {bridge_label}",
                    ),
                ))
        return cases

    def generate_detail_retrieval(self) -> list[TestCase]:
        """Pick leaf/terminal nodes — query requires their specific content."""
        cases: list[TestCase] = []
        leaves = [
            nid for nid, f in self.si.items()
            if "causal_terminal" in f.roles or
               (f.out_degree.get("leadsto", 0) == 0 and f.in_degree.get("leadsto", 0) > 0)
        ]
        for node_id in leaves[:8]:  # cap at 8
            label = self.labels.get(node_id, node_id)
            variants = _generate_query_variants(
                self._get_llm(), "detail_retrieval", label,
            )
            must_contain = self._node_anchor_words(node_id)[:3]
            for q in variants:
                cases.append(TestCase(
                    id=f"sd_{uuid.uuid4().hex[:8]}",
                    query=q,
                    query_type="detail_retrieval",
                    authored_by="structural_generator",
                    graph_id=self.graph_id,
                    source_node=node_id,
                    ground_truth=GroundTruth(
                        required_nodes=[node_id],
                        answer_must_contain=must_contain,
                        answerable=True,
                        difficulty="single_hop",
                        notes=f"Detail retrieval for leaf {label}",
                    ),
                ))
        return cases

    def generate_domain_survey(self) -> list[TestCase]:
        """Pick containment roots — query requires the subtree."""
        cases: list[TestCase] = []
        # Nodes with CONTAINS out-edges and no CONTAINS in-edges
        nodes_with_contains_out = set()
        nodes_with_contains_in = set()
        for nid, f in self.si.items():
            if f.out_degree.get("contains", 0) > 0:
                nodes_with_contains_out.add(nid)
            if f.in_degree.get("contains", 0) > 0:
                nodes_with_contains_in.add(nid)
        roots = nodes_with_contains_out - nodes_with_contains_in
        for root_id in list(roots)[:3]:
            label = self.labels.get(root_id, root_id)
            subtree = _get_contains_subtree(self.conn, root_id)
            if len(subtree) < 2:
                continue
            variants = _generate_query_variants(
                self._get_llm(), "domain_survey", label,
            )
            must_contain = self._node_anchor_words(root_id)[:2]
            for q in variants:
                cases.append(TestCase(
                    id=f"sds_{uuid.uuid4().hex[:8]}",
                    query=q,
                    query_type="domain_survey",
                    authored_by="structural_generator",
                    graph_id=self.graph_id,
                    source_node=root_id,
                    ground_truth=GroundTruth(
                        required_nodes=subtree,
                        answerable=True,
                        difficulty="domain_survey",
                        notes=f"Domain survey from root {label}, {len(subtree)} nodes",
                    ),
                ))
        return cases

    def generate_structural_overview(self) -> list[TestCase]:
        """Overview query — requires landmark nodes (top by betweenness)."""
        ranked = sorted(
            self.si.items(),
            key=lambda x: x[1].betweenness_centrality,
            reverse=True,
        )
        top_ids = [nid for nid, _ in ranked[:4] if ranked[0][1].betweenness_centrality > 0]
        if not top_ids:
            return []
        graph_id_label = self.graph_id.replace("_", " ").title()
        variants = _generate_query_variants(
            self._get_llm(), "structural_overview",
            graph_id_label,
            context="Ask for an overview or summary of the main concepts",
        )
        must_contain = []
        for nid in top_ids[:2]:
            must_contain += self._node_anchor_words(nid)[:1]
        cases = []
        for q in variants[:1]:  # Only 1 variant for overview
            cases.append(TestCase(
                id=f"sov_{uuid.uuid4().hex[:8]}",
                query=q,
                query_type="structural_overview",
                authored_by="structural_generator",
                graph_id=self.graph_id,
                source_node=top_ids[0],
                ground_truth=GroundTruth(
                    required_nodes=top_ids,
                    answer_must_contain=must_contain,
                    answerable=True,
                    difficulty="domain_survey",
                    notes=f"Overview — requires top {len(top_ids)} landmark nodes",
                ),
            ))
        return cases

    def generate_all(self) -> list[TestCase]:
        cases: list[TestCase] = []
        print("  Generating causal_forward cases...")
        cases += self.generate_causal_forward()
        print("  Generating causal_backward cases...")
        cases += self.generate_causal_backward()
        print("  Generating bridge cases...")
        cases += self.generate_bridge()
        print("  Generating detail_retrieval cases...")
        cases += self.generate_detail_retrieval()
        print("  Generating domain_survey cases...")
        cases += self.generate_domain_survey()
        print("  Generating structural_overview cases...")
        cases += self.generate_structural_overview()
        print(f"  Structural generator: {len(cases)} total cases.")
        return cases


