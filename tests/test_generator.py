class UnanswerableGenerator:
    """Generates queries the graph structurally cannot answer."""

    def __init__(self, conn: lb.Connection, structural_index: dict[str, StructuralFacts], graph_id: str):
        self.conn = conn
        self.si = structural_index
        self.graph_id = graph_id
        self.labels = _label_map(conn)
        self._llm: ChatOpenAI | None = None

    def _get_llm(self) -> ChatOpenAI:
        if self._llm is None:
            self._llm = _fast_llm()
        return self._llm

    def generate_absent_concepts(self, domain: str, count: int = 8) -> list[TestCase]:
        """Generate queries for concepts plausibly in the domain but absent from the graph."""
        existing_labels = list(self.labels.values())
        candidates = _generate_adjacent_absent_concepts(
            self._get_llm(), domain, existing_labels
        )
        # Confirm absence
        confirmed_absent = [c for c in candidates if not _concept_in_graph(self.conn, c)]
        cases = []
        for concept in confirmed_absent[:count]:
            # Generate a simple query for each absent concept
            variants = _generate_query_variants(
                self._get_llm(), "unanswerable_absent", concept,
                context=f"Domain: {domain}",
            )
            for q in variants[:1]:  # 1 variant per absent concept
                cases.append(TestCase(
                    id=f"ua_{uuid.uuid4().hex[:8]}",
                    query=q,
                    query_type="unanswerable_absent",
                    authored_by="unanswerable_generator",
                    graph_id=self.graph_id,
                    source_node="",
                    ground_truth=GroundTruth(
                        required_nodes=[],
                        answerable=False,
                        expected_gap_contains=concept,
                        answer_must_not_contain=[concept.lower()],
                        notes=f"Absent concept: '{concept}' — confirmed not in graph",
                    ),
                ))
        return cases

    def generate_partial_knowledge(self) -> list[TestCase]:
        """Generate queries about aspects structurally absent even though the domain is present.

        Two patterns:
        1. Causal nexus with no EXPRESSES edges → query about its attributes/properties
        2. Causal chain terminal → query about what comes after
        """
        cases = []

        # Pattern 1: causal_nexus with no EXPRESSES out-edges
        for nid, f in self.si.items():
            if "causal_nexus" in f.roles and f.out_degree.get("expresses", 0) == 0:
                label = self.labels.get(nid, nid)
                q = f"What are the specific measurable indicators or attributes of {label}?"
                cases.append(TestCase(
                    id=f"up_{uuid.uuid4().hex[:8]}",
                    query=q,
                    query_type="unanswerable_partial",
                    authored_by="unanswerable_generator",
                    graph_id=self.graph_id,
                    source_node=nid,
                    ground_truth=GroundTruth(
                        required_nodes=[nid],
                        answerable=False,
                        expected_gap_contains="measurable indicators",
                        notes=f"{label} is a causal_nexus with no EXPRESSES edges — attributes not modelled",
                    ),
                ))

        # Pattern 2: causal_terminal with forward LEADSTO out-degree == 0 → what comes next?
        for nid, f in self.si.items():
            if "causal_terminal" in f.roles and f.out_degree.get("leadsto", 0) == 0:
                label = self.labels.get(nid, nid)
                q = f"What are the downstream consequences or treatments for {label}?"
                cases.append(TestCase(
                    id=f"up_{uuid.uuid4().hex[:8]}",
                    query=q,
                    query_type="unanswerable_partial",
                    authored_by="unanswerable_generator",
                    graph_id=self.graph_id,
                    source_node=nid,
                    ground_truth=GroundTruth(
                        required_nodes=[nid],
                        answerable=False,
                        expected_gap_contains="downstream",
                        notes=f"{label} is a causal_terminal — no outgoing LEADSTO edges model what comes next",
                    ),
                ))
        return cases[:10]  # cap

    def generate_all(self, domain: str) -> list[TestCase]:
        cases = []
        print(f"  Generating absent_concept cases for domain '{domain}'...")
        cases += self.generate_absent_concepts(domain)
        print("  Generating partial_knowledge cases...")
        cases += self.generate_partial_knowledge()
        print(f"  Unanswerable generator: {len(cases)} total cases.")
        return cases


