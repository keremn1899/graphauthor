def _all_nodes(conn: lb.Connection) -> list[dict]:
    rows = list(conn.execute(
        "MATCH (c:Concept) RETURN c.id, c.label, c.semantic_anchor, c.is_metanode"
    ))
    return [{"id": r[0], "label": r[1], "anchor": r[2] or "", "is_metanode": r[3]} for r in rows]


def _label_map(conn: lb.Connection) -> dict[str, str]:
    return {n["id"]: n["label"] for n in _all_nodes(conn)}


def _traverse_chain(
    conn: lb.Connection,
    start_id: str,
    direction: Literal["forward", "backward"],
    sst_type: str,
    max_depth: int = 4,
) -> list[str]:
    """BFS chain walk — returns ordered list of node IDs (including start)."""
    visited = [start_id]
    current = start_id
    for _ in range(max_depth):
        nbs = get_neighbours(conn, current, sst_type, direction)
        if not nbs:
            break
        # Follow the first unvisited neighbour
        next_node = next((nb["id"] for nb in nbs if nb["id"] not in visited), None)
        if not next_node:
            break
        visited.append(next_node)
        current = next_node
    return visited


def _get_contains_subtree(conn: lb.Connection, root_id: str) -> list[str]:
    """BFS over CONTAINS edges forward from root."""
    visited = [root_id]
    queue = [root_id]
    while queue:
        current = queue.pop(0)
        children = get_neighbours(conn, current, "contains", "forward")
        for child in children:
            if child["id"] not in visited:
                visited.append(child["id"])
                queue.append(child["id"])
    return visited


def _format_trail(node_ids: list[str], labels: dict[str, str], sst_type: str = "LEADSTO") -> list[str]:
    trail = []
    for i in range(len(node_ids) - 1):
        trail.append(f"{labels.get(node_ids[i], node_ids[i])} --{sst_type}--> {labels.get(node_ids[i+1], node_ids[i+1])}")
    return trail


def _concept_in_graph(conn: lb.Connection, concept: str) -> bool:
    """Check if a concept label appears anywhere in the graph (case-insensitive substring match)."""
    concept_lower = concept.lower()
    rows = list(conn.execute(
        "MATCH (c:Concept) RETURN c.label, c.semantic_anchor, c.text_content"
    ))
    for r in rows:
        label, anchor, content = (r[0] or "").lower(), (r[1] or "").lower(), (r[2] or "").lower()
        if concept_lower in label or concept_lower in anchor[:200]:
            return True
    return False


