"""SST test case generator.

Generates structural and unanswerable test cases from a live LadybugDB graph.
Ground truth is derived from graph structure — not LLM inference.
Query text is generated by a fast LLM as natural language variants of each
structural template.

Usage:
    conda run -n agentic-graphrag python tests/test_generator.py \
        --seed metabolism --out tests/test_sets/metabolism/

Output: tests/test_sets/<graph_id>/{structural,unanswerable}_tests.json
"""

