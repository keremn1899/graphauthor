def _detect_domain(conn: lb.Connection) -> str:
    """Infer a short domain description from the graph's node labels."""
    rows = list(conn.execute("MATCH (c:Concept) RETURN c.label LIMIT 5"))
    labels = [r[0] for r in rows]
    return ", ".join(labels[:3])


