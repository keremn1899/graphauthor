@dataclass
class GroundTruth:
    required_nodes: list[str] = field(default_factory=list)
    required_trail: list[str] = field(default_factory=list)      # e.g. ["n_001 --LEADSTO--> n_003"]
    answer_must_contain: list[str] = field(default_factory=list)
    answer_must_not_contain: list[str] = field(default_factory=list)
    expected_gap_contains: str = ""   # concept text that should appear in gap inventory
    answerable: bool = True
    difficulty: Literal["single_hop", "multi_hop", "bridge", "domain_survey"] = "multi_hop"
    notes: str = ""


@dataclass
class TestCase:
    id: str
    query: str
    query_type: Literal[
        "causal_forward", "causal_backward", "bridge",
        "detail_retrieval", "domain_survey", "structural_overview",
        "cross_domain", "unanswerable_absent", "unanswerable_partial",
    ]
    authored_by: Literal["structural_generator", "unanswerable_generator", "ai_curated"]
    graph_id: str
    source_node: str
    ground_truth: GroundTruth = field(default_factory=GroundTruth)


def _tc_to_dict(tc: TestCase) -> dict:
    d = asdict(tc)
    return d


def save_test_cases(cases: list[TestCase], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump([_tc_to_dict(c) for c in cases], f, indent=2)
    print(f"  Saved {len(cases)} test cases → {path}")


def load_test_cases(path: Path) -> list[dict]:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


