def _fast_llm() -> ChatOpenAI:
    return ChatOpenAI(
        model=os.environ.get("FAST_MODEL", "google/gemini-3.1-flash-lite-preview"),
        temperature=0.7,
        max_tokens=400,
        api_key=os.environ["OPENROUTER_API_KEY"],
        base_url="https://openrouter.ai/api/v1",
    )


_QUERY_SYSTEM = """\
You generate natural language question variants for a knowledge graph test suite.
You receive a template type, a subject concept, and optional context.
Generate exactly 3 different natural language questions that all ask the same thing.
Vary phrasing only — not meaning. Each question should sound like something a real user would ask.
Do not include the answer. Do not reference graph structure, node IDs, or edge types.
Return ONLY a JSON array of 3 strings.
"""


def _generate_query_variants(llm: ChatOpenAI, template: str, subject: str, context: str = "") -> list[str]:
    """Generate 3 natural language phrasings for a given structural template."""
    prompt = (
        f"Template: {template}\n"
        f"Subject: {subject}\n"
    )
    if context:
        prompt += f"Context: {context}\n"
    try:
        resp = llm.invoke([
            SystemMessage(content=_QUERY_SYSTEM),
            HumanMessage(content=prompt),
        ])
        text = (resp.content if hasattr(resp, "content") else str(resp)).strip()
        if "```" in text:
            text = text.split("```")[1]
            if text.startswith("json"):
                text = text[4:]
        variants = json.loads(text)
        if isinstance(variants, list) and len(variants) >= 1:
            return [str(v) for v in variants[:3]]
    except Exception as e:
        print(f"    Warning: query variant generation failed ({e}). Using template fallback.")
    # Fallback — simple template-based query
    fallback_map = {
        "causal_forward": f"What does {subject} lead to?",
        "causal_backward": f"What causes {subject}?",
        "bridge": f"How are the concepts in {subject} connected?",
        "detail_retrieval": f"What is {subject}?",
        "domain_survey": f"What are the components of {subject}?",
        "structural_overview": f"What are the most important concepts in this graph?",
        "unanswerable_absent": f"What is the role of {subject}?",
        "unanswerable_partial": f"What happens after {subject}?",
    }
    return [fallback_map.get(template, f"Tell me about {subject}.")]


_ABSENT_CONCEPT_SYSTEM = """\
You generate concept names that are plausibly related to a domain but are NOT present in the given graph.
These will be used as unanswerable test queries — the system should report a gap, not confabulate.
Return ONLY a JSON array of concept label strings (10-15 items).
Make them specific enough that a system with partial domain knowledge might be tempted to answer.
"""


def _generate_adjacent_absent_concepts(llm: ChatOpenAI, domain: str, existing_labels: list[str]) -> list[str]:
    """Generate concepts plausibly related to the domain but absent from the graph."""
    existing_str = ", ".join(existing_labels[:20])
    prompt = (
        f"Domain: {domain}\n"
        f"Concepts already in the graph: {existing_str}\n"
        "Generate 12 concepts that are plausibly related to this domain but are NOT in the list above."
    )
    try:
        resp = llm.invoke([
            SystemMessage(content=_ABSENT_CONCEPT_SYSTEM),
            HumanMessage(content=prompt),
        ])
        text = (resp.content if hasattr(resp, "content") else str(resp)).strip()
        if "```" in text:
            text = text.split("```")[1]
            if text.startswith("json"):
                text = text[4:]
        concepts = json.loads(text)
        if isinstance(concepts, list):
            return [str(c) for c in concepts]
    except Exception as e:
        print(f"    Warning: absent concept generation failed ({e}).")
    return []


